// Normalized lookup set per company for O(1) matching
const NORMALIZED_MAP: Record<string, Set<string>> = {};
for (const [company, list] of Object.entries(COMPANY_QUESTIONS)) {
  NORMALIZED_MAP[company] = new Set(list.map(normalize));
}

/**
 * Returns matching company IDs for a problem based on its title and tags.
 */
export function getCompaniesForProblem(title: string, tags: string[] = []): string[] {
  const normTitle = normalize(title);
  const matched = new Set<string>();

  for (const [company, titleSet] of Object.entries(NORMALIZED_MAP)) {
    if (titleSet.has(normTitle)) {
      matched.add(company);
    }
  }

  // Also match by partial title heuristics for common multi-part titles
  for (const [company, questions] of Object.entries(COMPANY_QUESTIONS)) {
    for (const q of questions) {
      const normQ = normalize(q);
      if (normTitle.length > 5 && (normTitle === normQ || normTitle.startsWith(normQ) || normQ.startsWith(normTitle))) {
        matched.add(company);
        break;
      }
    }
  }

  return Array.from(matched);
}
